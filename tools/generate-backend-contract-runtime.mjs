import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve, relative } from "node:path";

const root = resolve(process.cwd());
const check = process.argv.includes("--check");
const openApi = JSON.parse(
  await readFile(resolve(root, "contracts/openapi-1.0.json"), "utf8"),
);
const productionRoot = resolve(root, "apps/api/src/production");
const generatedRoot = resolve(productionRoot, "contract-runtime/generated");
const existingFiles = (await collectFiles(productionRoot)).filter(
  (file) => file.endsWith(".controller.ts") && !file.startsWith(generatedRoot),
);
const occupied = new Map();
for (const file of existingFiles) {
  const source = await readFile(file, "utf8");
  const prefix = source.match(/@Controller\("([^"]*)"\)/u)?.[1] ?? "";
  const pattern = /@(Get|Post|Put|Patch|Delete)(?:\("([^"]*)"\)|\(\))([\s\S]*?)(?=\n\s*(?:async\s+)?[A-Za-z_$][\w$]*\s*\()/gu;
  for (const match of source.matchAll(pattern)) {
    const method = match[1].toUpperCase();
    const route = match[2] ?? "";
    const operationId = match[3].match(/@OperationId\("([^"]+)"\)/u)?.[1] ?? null;
    occupied.set(`${method} ${normalizePath(`/${prefix}/${route}`)}`, {
      operationId,
      file: relative(root, file),
    });
  }
}

const targetOperations = [];
for (const [publicPath, pathItem] of Object.entries(openApi.paths ?? {})) {
  for (const [methodName, operation] of Object.entries(pathItem)) {
    if (!["get", "post", "put", "patch", "delete"].includes(methodName)) continue;
    if (!operation || typeof operation.operationId !== "string") continue;
    const servicePath = normalizePath(publicPath.replace(/^\/api/u, ""));
    targetOperations.push({
      operationId: operation.operationId,
      method: methodName.toUpperCase(),
      servicePath,
      route: servicePath.replace(/^\//u, "").replace(/\{([^}]+)\}/gu, ":$1"),
    });
  }
}
targetOperations.sort((a, b) => a.operationId.localeCompare(b.operationId));

const generated = [];
for (const operation of targetOperations) {
  const key = `${operation.method} ${operation.servicePath}`;
  const existing = occupied.get(key);
  if (existing) {
    if (existing.operationId !== operation.operationId) {
      throw new Error(
        `Target route ${key} is occupied by ${existing.operationId ?? "no operationId"} in ${existing.file}; expected ${operation.operationId}.`,
      );
    }
    continue;
  }
  generated.push(operation);
}

const groups = new Map();
for (const operation of generated) {
  const segment = operation.servicePath.split("/").filter(Boolean)[1] ?? "misc";
  const group = groupFor(segment);
  const list = groups.get(group) ?? [];
  list.push(operation);
  groups.set(group, list);
}

const outputs = [];
const classNames = [];
for (const [group, operations] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
  const className = `${pascal(group)}ContractController`;
  classNames.push({ className, file: `./${group}.controller.js` });
  outputs.push([
    resolve(generatedRoot, `${group}.controller.ts`),
    renderController(className, operations),
  ]);
}
outputs.push([
  resolve(generatedRoot, "index.ts"),
  renderIndex(classNames),
]);

let mismatch = false;
for (const [path, content] of outputs) {
  if (check) {
    const current = await readFile(path, "utf8").catch(() => "");
    if (current !== content) {
      console.error(`CONTRACT_RUNTIME_DRIFT=${relative(root, path)}`);
      mismatch = true;
    }
  } else {
    await writeFile(path, content, "utf8");
  }
}
if (mismatch) process.exitCode = 1;
else {
  console.log(
    `BACKEND_CONTRACT_RUNTIME=PASS target=${targetOperations.length} generated=${generated.length} native=${targetOperations.length - generated.length}`,
  );
}

function renderController(className, operations) {
  const methods = operations.map(renderMethod).join("\n");
  const nestImports = [
    "Controller",
    "Inject",
    "Headers",
    "Req",
    ...new Set(operations.map((operation) => decoratorFor(operation.method))),
  ].sort();
  const hasPublic = operations.some((operation) => isPublicOperation(operation.operationId));
  const hasAuthenticated = operations.some((operation) => !isPublicOperation(operation.operationId));
  const policyImports = [
    "OperationId",
    ...(hasPublic ? ["PublicEndpoint"] : []),
    ...(hasAuthenticated ? ["AuditDeniedAccess", "RequireAuthLevel", "RequireCapabilities"] : []),
  ].sort();
  return `// Generated by tools/generate-backend-contract-runtime.mjs. Do not edit manually.
import { ${nestImports.join(", ")} } from "@nestjs/common";
import type { FastifyRequest } from "fastify";
import { ${policyImports.join(", ")} } from "../../auth/route-policy.js";
${hasAuthenticated ? 'import { Principal } from "../../auth/principal.decorator.js";\nimport type { RequestPrincipal } from "../../auth/request-principal.js";\n' : ''}import { ContractRuntimeService } from "../contract-runtime.service.js";
import { contractRequest } from "../contract-runtime.request.js";

@Controller()
export class ${className} {
  constructor(
    @Inject(ContractRuntimeService) private readonly runtime: ContractRuntimeService,
  ) {}
${methods}}
`;
}

function renderMethod(operation, index) {
  const decorator = decoratorFor(operation.method);
  const publicOperation = isPublicOperation(operation.operationId);
  const capability = capabilityFor(operation.operationId, operation.method);
  const authLevel = authLevelFor(operation.operationId, operation.method);
  const methodName = `${safeIdentifier(operation.operationId)}_${index + 1}`;
  const policy = publicOperation
    ? "  @PublicEndpoint()\n"
    : `  @RequireCapabilities("${capability}")\n${authLevel === "session" ? "" : `  @RequireAuthLevel("${authLevel}")\n`}${operation.method === "GET" ? "" : "  @AuditDeniedAccess()\n"}`;
  const signature = publicOperation
    ? `    @Req() request: FastifyRequest,\n    @Headers("x-correlation-id") correlationId?: string,\n    @Headers("idempotency-key") idempotencyKey?: string,`
    : `    @Principal() principal: RequestPrincipal,\n    @Req() request: FastifyRequest,\n    @Headers("x-correlation-id") correlationId?: string,\n    @Headers("idempotency-key") idempotencyKey?: string,`;
  const invocation = publicOperation
    ? `return this.runtime.executePublic(contractRequest("${operation.operationId}", "${operation.method}", "${operation.servicePath}", request, correlationId, idempotencyKey), {\n      correlationId: correlationId ?? null,\n      ipAddress: request.ip ?? null,\n    });`
    : `return this.runtime.executeAuthenticated(\n      principal,\n      contractRequest("${operation.operationId}", "${operation.method}", "${operation.servicePath}", request, correlationId, idempotencyKey),\n    );`;
  return `\n  @${decorator}("${operation.route}")\n  @OperationId("${operation.operationId}")\n${policy}  ${methodName}(\n${signature}\n  ): Promise<object> {\n    ${invocation}\n  }\n`;
}

function renderIndex(classes) {
  const imports = classes.map(({ className, file }) => `import { ${className} } from "${file}";`).join("\n");
  const exports = classes.map(({ className, file }) => `export { ${className} } from "${file}";`).join("\n");
  return `// Generated by tools/generate-backend-contract-runtime.mjs. Do not edit manually.\n${imports}\n\n${exports}\n\nexport const contractRuntimeControllers = [\n${classes.map(({ className }) => `  ${className},`).join("\n")}\n] as const;\n`;
}

function groupFor(segment) {
  if (["access", "auth", "company", "invitation", "mobile", "onboarding", "workspace"].includes(segment)) return "identity-access";
  if (["billing"].includes(segment)) return "billing";
  if (["campaigns", "command-center", "customers", "orders", "products", "traffic"].includes(segment)) return "commerce-analytics";
  if (["actions", "data-quality", "decisions", "papa"].includes(segment)) return "data-decisions";
  if (["integrations"].includes(segment)) return "integrations";
  return "support-settings";
}

function isPublicOperation(operationId) {
  return new Set([
    "auth.access.blocked.read",
    "auth.email.resend",
    "auth.email.verify",
    "auth.login",
    "auth.oauth.callback",
    "auth.oauth.start",
    "auth.password.recovery.request",
    "auth.password.recovery.token.validate",
    "auth.password.reset",
    "auth.register.email",
    "auth.registration.finalize",
    "auth.status.read",
    "company.lookup",
    "invitation.accept",
    "invitation.validate",
  ]).has(operationId);
}

function capabilityFor(operationId, method) {
  const write = method !== "GET";
  if (operationId.startsWith("billing.")) return write ? "billing.manage" : "billing.read";
  if (operationId.startsWith("integrations.")) {
    if (operationId.includes("catalog")) return "integrations.catalog.read";
    if (operationId.includes("sync") || operationId.includes("reconnect")) return write ? "integrations.sync.run" : "integrations.jobs.read";
    return write ? "integrations.connection.manage" : "integrations.connection.read";
  }
  if (operationId.startsWith("papa.") || operationId.startsWith("decisions.") || operationId.startsWith("actions.")) {
    if (!write) return operationId.includes("governance") ? "ai.governance.read" : "ai.history.read";
    if (operationId.includes("approve")) return "ai.action_proposal.approve";
    if (operationId.includes("execute") || operationId.includes("rollback")) return "ai.action_proposal.execute";
    return "ai.action_proposal.create";
  }
  if (operationId.startsWith("auth.mfa.")) return write ? "auth.mfa.enroll" : "auth.session.read";
  if (operationId.startsWith("auth.")) return write ? "auth.session.revoke" : "auth.session.read";
  if (operationId.startsWith("customers.privacy") || operationId.startsWith("customers.pseudonymized")) return "privacy.audit.read";
  if (operationId.startsWith("settings.audit")) return "audit.read";
  if (operationId.startsWith("settings.memberships") || operationId.startsWith("invitation.")) return write ? "tenant.membership.manage" : "tenant.membership.read";
  if (operationId.startsWith("access.")) return write ? "workspace.manage" : "workspace.read";
  if (["campaigns", "command-center", "customers", "data-quality", "orders", "products", "traffic"].some((prefix) => operationId.startsWith(`${prefix}.`))) {
    return write ? "workspace.manage" : operationId.startsWith("command-center.") ? "analytics.command_center.read" : "analytics.metrics.read";
  }
  return write ? "workspace.manage" : "workspace.read";
}

function authLevelFor(operationId, method) {
  if (method === "GET") return "session";
  if (/approve|execute|rollback|payment|password|mfa|invitation|billing|account-security|support-access/iu.test(operationId)) return "step_up";
  return "mfa";
}

function decoratorFor(method) {
  return { DELETE: "Delete", GET: "Get", PATCH: "Patch", POST: "Post", PUT: "Put" }[method];
}
function normalizePath(value) {
  return value.replace(/\/+/gu, "/").replace(/\/$/u, "") || "/";
}
function safeIdentifier(value) {
  return value.replace(/[^A-Za-z0-9_$]/gu, "_").replace(/^[^A-Za-z_$]/u, "_$&");
}
function pascal(value) {
  return value.split(/[^A-Za-z0-9]+/u).filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join("");
}
async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const result = [];
  for (const entry of entries) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) result.push(...await collectFiles(path));
    else if (entry.isFile()) result.push(path);
  }
  return result;
}
